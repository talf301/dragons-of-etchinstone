export const replacements = rows.map(
  (
    [
      name,
      bg,
      basic,
      enhanced,
      ether,
      cost,
      init,
      boost,
      bval,
      evals,
      armor,
      shield,
      key,
    ],
    id,
  ) => {
    const backgrounds = bg.includes(" ") ? bg.split(" ") : [...bg];
    const levels = {};
    for (let i = 0; i < 4; i++)
      levels[i + 1] = {
        background: [...backgrounds[i]].map((c) => colors[c]),
        initiative: +init[i],
        boost: +boost[i],
        upgradeCost: +cost[i],
        basic: { type: actions[basic], value: +bval[i] },
        enhanced: {
          type: actions[enhanced],
          value: +evals[i],
          element: colors[ether[0]],
          colors: [...ether].map((c) => colors[c]),
        },
        armorValue: +armor[i],
        armorElement: colors[shield[i]],
        encounterIcon: journeys.has(id) ? "journey" : "enemy",
        encounterValue: +key[i],
        hardship:
          (id === 2 && i === 3) || (id === 4 && i === 0)
            ? "hazards"
            : id === 7 && i === 0
              ? "storm"
              : "none",
      };
    return { name, mage: mages[roster[id]], levels };
  },
);
